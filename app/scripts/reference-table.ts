/**
 * Prints (and saves to ../evidence/engine_vs_reference.md, creating the folder if
 * needed) a table comparing the TypeScript engine with the published reference
 * values (project report §3). Run from app/:  npm run reference-table
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { calculate, type Results } from '../src/lib/finance';
import { PRESETS, type PresetId } from '../src/lib/scenarios';
import { formatPctChange, formatPp, formatRate, formatSpot } from '../src/lib/format';

type Row = { id: PresetId; key: keyof Results; label: string; ref: number; dp: number; fmt: (v: number) => string };

const spot = (v: number) => `${formatSpot(v)} MYR/USD`;
const rows: Row[] = [];
function add(id: PresetId, key: keyof Results, label: string, ref: number, dp: number, fmt: (v: number) => string) {
  rows.push({ id, key, label, ref, dp, fmt });
}

// Reference values exactly as printed in the project report (dp = decimals printed there).
const SIX: [PresetId, number, number, number, number, number, number][] = [
  // id, i_MY, i_US, diff pp, PPP, quote %, MYR value %
  ['A', 4.0375, 4.545, -0.5075, 4.3786407767, -0.4854368932, 0.487804878],
  ['B', 4.0375, 6.575, -2.5375, 4.2952380952, -2.380952381, 2.4390243902],
  ['C', 4.0375, 4.0375, 0, 4.4, 0, 0],
  ['D', 6.575, 4.0375, 2.5375, 4.5073, 2.439, -2.381],
  ['E', 9.62, 2.515, 7.105, 4.705, 6.9307, -6.4815],
  ['F', 2.515, 9.62, -7.105, 4.1148, -6.4815, 6.9307],
];
for (const [id, iMY, iUS, diff, ppp, quote, value] of SIX) {
  const precise = id === 'A' || id === 'B';
  add(id, 'nominalMYPct', 'i_MY (%)', iMY, 4, formatRate);
  add(id, 'nominalUSPct', 'i_US (%)', iUS, 4, formatRate);
  add(id, 'nominalDiffPp', 'i_MY − i_US (pp)', diff, 4, formatPp);
  add(id, 'pppSpot', 'PPP spot', ppp, precise ? 10 : 4, spot);
  add(id, 'cipForward', 'CIP forward', ppp, precise ? 10 : 4, spot);
  add(id, 'quoteChangePct', 'Quote change (%)', quote, precise ? 10 : 4, formatPctChange);
  add(id, 'myrValueChangePct', 'MYR value change (%)', value, precise ? 10 : 4, formatPctChange);
}
add('ADV', 'nominalUSPct', 'i_US (%) — r_US 2.5%', 5.575, 4, formatRate);
add('ADV', 'pppSpot', 'PPP spot', 4.3786407767, 10, spot);
add('ADV', 'cipForward', 'CIP forward', 4.3359223301, 10, spot);
add('B', 'quoteChangeApproxPct', 'Approx. quote change (%)', -2.5, 4, formatPctChange);
add('B', 'approxErrorPp', 'Approx − exact (pp)', -0.119, 4, formatPp);
add('A', 'nominalMYApproxPct', 'Fisher approx r + π (%)', 4.0, 4, formatRate);

const lines = [
  '| Case | Quantity | Reference (as printed) | Engine, unrounded | Engine display | Match |',
  '|---|---|---:|---:|---:|:---:|',
];
let failures = 0;
for (const r of rows) {
  const v = calculate(PRESETS[r.id].inputs)[r.key] as number;
  // A printed reference with d decimals matches if the engine rounds to it at d decimals.
  const ok = Number(v.toFixed(r.dp)) === Number(r.ref.toFixed(r.dp));
  if (!ok) failures += 1;
  lines.push(
    `| ${r.id} | ${r.label} | ${r.ref.toFixed(r.dp)} | ${v.toFixed(10)} | ${r.fmt(v)} | ${ok ? 'yes' : '**NO**'} |`,
  );
}
lines.push('', `${rows.length} comparisons, ${failures} mismatches.`);
const text = lines.join('\n');
console.log(text);
const outDir = resolve(process.cwd(), '../evidence');
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'engine_vs_reference.md'), `# Engine vs reference values\n\nGenerated by \`npm run reference-table\` (app/scripts/reference-table.ts) on ${new Date().toISOString().slice(0, 10)}.\n"Reference (as printed)" uses the number of decimals printed in the project report; a row matches when the unrounded engine value rounds to it.\n\n${text}\n`);
process.exit(failures === 0 ? 0 : 1);
